import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";
import * as XLSX from "xlsx";

const RED = [200, 33, 58];
const n2 = (v) => Number(v || 0).toFixed(2);

function header(doc, title, data) {
  const fx = data.items.find((i) => i.currency === "USD")?.fx_rate;
  const w = doc.internal.pageSize.getWidth();
  doc.setFillColor(...RED); doc.rect(0, 0, w, 22, "F");
  doc.setTextColor(255); doc.setFont("helvetica", "bold"); doc.setFontSize(15);
  doc.text("IPTAS", 14, 14);
  doc.setFont("helvetica", "normal"); doc.setFontSize(9);
  doc.text(data.company || "", w - 14, 14, { align: "right" });
  doc.setTextColor(34); doc.setFont("helvetica", "bold"); doc.setFontSize(14);
  doc.text(title, 14, 34);
  doc.setFont("helvetica", "normal"); doc.setFontSize(9.5); doc.setTextColor(90);
  doc.text(`Pay period: ${data.period.start_date} to ${data.period.end_date}    Pay date: ${data.period.pay_date}    Status: ${data.period.status}`, 14, 41);
  doc.text(`Pay rules: ${data.rule.rule_name} – OT after ${data.rule.overtime_threshold} h/week x ${data.rule.overtime_multiplier}, CPP ${(data.rule.cpp_rate * 100).toFixed(2)}%, EI ${(data.rule.ei_rate * 100).toFixed(2)}%${fx ? `, USD->CAD ${fx}` : ""}`, 14, 47);
}

function footer(doc) {
  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i); doc.setFontSize(8); doc.setTextColor(120);
    const w = doc.internal.pageSize.getWidth(), h = doc.internal.pageSize.getHeight();
    doc.text(`Generated by IPTAS on ${new Date().toLocaleString("en-CA")}`, 14, h - 8);
    doc.text(`Page ${i} of ${pages}`, w - 14, h - 8, { align: "right" });
  }
}

export function summaryPdf(data) {
  const doc = new jsPDF({ orientation: "landscape" });
  header(doc, "Payroll Summary Report", data);
  const body = data.items.map((i) => [i.full_name, i.employment_type, i.currency, n2(i.regular_hours), n2(i.overtime_hours), n2(i.gross_pay), n2(i.cpp_deduction), n2(i.ei_deduction), n2(i.net_pay), n2(i.net_pay_cad)]);
  const sum = (k) => n2(data.items.reduce((a, i) => a + Number(i[k]), 0));
  autoTable(doc, {
    startY: 53,
    head: [["Employee", "Type", "Cur.", "Reg. hrs", "OT hrs", "Gross", "CPP", "EI", "Net pay", "Net (CAD)"]],
    body,
    foot: [["TOTAL", "", "", sum("regular_hours"), sum("overtime_hours"), "", "", "", "", sum("net_pay_cad")].map((c, k) => ({ content: c, styles: { halign: k >= 3 ? "right" : "left" } }))],
    headStyles: { fillColor: [34, 34, 34] }, footStyles: { fillColor: RED },
    styles: { fontSize: 9 }, columnStyles: { 3: { halign: "right" }, 4: { halign: "right" }, 5: { halign: "right" }, 6: { halign: "right" }, 7: { halign: "right" }, 8: { halign: "right" }, 9: { halign: "right" } },
  });
  footer(doc);
  return doc;
}

export function payslipsPdf(data) {
  const doc = new jsPDF();
  data.items.forEach((i, idx) => {
    if (idx) doc.addPage();
    header(doc, `Payslip – ${i.full_name}`, data);
    autoTable(doc, {
      startY: 55, theme: "grid",
      head: [["Item", "Hours", `Amount (${i.currency})`]],
      body: [
        ["Regular hours", n2(i.regular_hours), ""],
        ["Overtime hours", n2(i.overtime_hours), ""],
        ["Gross pay", "", n2(i.gross_pay)],
        ["CPP deduction", "", Number(i.cpp_deduction) ? "-" + n2(i.cpp_deduction) : "0.00"],
        ["EI deduction", "", Number(i.ei_deduction) ? "-" + n2(i.ei_deduction) : "0.00"],
        ["Net pay", "", n2(i.net_pay)],
        ...(i.currency === "USD" ? [[`Net pay in CAD (x ${i.fx_rate})`, "", n2(i.net_pay_cad)]] : []),
      ],
      headStyles: { fillColor: RED }, styles: { fontSize: 10 }, columnStyles: { 1: { halign: "right" }, 2: { halign: "right" } },
    });
    const y = doc.lastAutoTable.finalY + 10;
    doc.setFontSize(9); doc.setTextColor(90);
    doc.text(`Employment type: ${i.employment_type}    Pay rate: ${n2(i.pay_rate)} ${i.currency}${i.employment_type === "hourly" ? "/hour" : "/period"}`, 14, y);
    doc.text(`Computed by: ${i.computed_by_name || "-"}    Approved by: ${i.approved_by_name || "Not yet approved"}`, 14, y + 6);
  });
  footer(doc);
  return doc;
}

export function summaryExcel(data) {
  const rows = data.items.map((i) => ({
    Employee: i.full_name, Email: i.email, Type: i.employment_type, Currency: i.currency,
    "Regular Hours": Number(i.regular_hours), "Overtime Hours": Number(i.overtime_hours), "Gross Pay": Number(i.gross_pay),
    CPP: Number(i.cpp_deduction), EI: Number(i.ei_deduction), "Net Pay": Number(i.net_pay), "FX Rate": Number(i.fx_rate), "Net Pay (CAD)": Number(i.net_pay_cad), Status: i.status,
  }));
  const wb = XLSX.utils.book_new();
  const info = XLSX.utils.aoa_to_sheet([
    ["IPTAS Payroll Summary"], ["Company", data.company], ["Pay period", `${data.period.start_date} to ${data.period.end_date}`],
    ["Pay date", data.period.pay_date], ["Status", data.period.status], ["Pay rules", data.rule.rule_name],
    ["Total net pay (CAD)", rows.reduce((a, r) => a + r["Net Pay (CAD)"], 0)],
  ]);
  const ws = XLSX.utils.json_to_sheet(rows);
  ws["!cols"] = [{ wch: 22 }, { wch: 28 }, { wch: 8 }, { wch: 8 }, ...Array(9).fill({ wch: 13 })];
  XLSX.utils.book_append_sheet(wb, info, "Summary");
  XLSX.utils.book_append_sheet(wb, ws, "Payroll");
  return wb;
}

export function saveExcel(wb, name) { XLSX.writeFile(wb, name); }
