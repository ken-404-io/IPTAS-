import { useEffect, useState } from "react";
import { api, fmtDateTime, periodLabel } from "../api.js";
import { PageHeader, Alert, Empty, PeriodSelect } from "../components/ui.jsx";
import usePeriods from "../components/usePeriods.js";
import Icon from "../components/Icon.jsx";
import { summaryPdf, payslipsPdf, summaryExcel, saveExcel } from "../exports.js";

const TYPES = [
  { id: "Payroll Summary", desc: "One table with every employee's hours, gross pay, deductions and net pay for the pay period." },
  { id: "Employee Payslips", desc: "One payslip page per employee with hours, gross pay, CPP, EI and net pay." },
];

export default function Reports() {
  const { periods, periodId, setPeriodId } = usePeriods();
  const [history, setHistory] = useState([]);
  const [err, setErr] = useState(""); const [msg, setMsg] = useState("");
  const loadHistory = () => api("/reports").then(setHistory).catch(() => {});
  useEffect(() => { loadHistory(); }, []);

  const generate = async (type, format) => {
    setErr(""); setMsg("");
    try {
      const data = await api(`/payroll/${periodId}`);
      if (!data.items.length) throw new Error("No payroll has been computed for this period yet.");
      const base = `IPTAS_${type.replace(/ /g, "_")}_${data.period.start_date}_to_${data.period.end_date}`;
      let name;
      if (format === "PDF") { name = base + ".pdf"; (type === "Payroll Summary" ? summaryPdf(data) : payslipsPdf(data)).save(name); }
      else {
        if (type !== "Payroll Summary") throw new Error("Payslips are available as PDF. Use the Payroll Summary for Excel.");
        name = base + ".xlsx"; saveExcel(summaryExcel(data), name);
      }
      await api("/reports", { method: "POST", body: { period_id: periodId, report_type: type, file_format: format, file_path: name } });
      setMsg(`${name} downloaded.`); loadHistory();
    } catch (e) { setErr(e.message); }
  };
  const p = periods.find((x) => x.period_id === periodId);
  return (
    <>
      <PageHeader title="Payroll Reports" subtitle="Generate reports per pay period and export them to PDF or Excel.">
        <PeriodSelect periods={periods} value={periodId} onChange={setPeriodId} />
      </PageHeader>
      <Alert>{err}</Alert><Alert kind="success">{msg}</Alert>
      {p && p.status !== "approved" && <Alert kind="info">This pay period is not approved yet, so reports will be marked “{p.status}”.</Alert>}
      <div className="grid2">
        {TYPES.map((t) => (
          <section className="card report-card" key={t.id}>
            <div className="report-icon"><Icon name="file" size={26} /></div>
            <h3>{t.id}</h3><p className="muted">{t.desc}</p>
            <div className="btn-row">
              <button className="btn primary" onClick={() => generate(t.id, "PDF")}><Icon name="download" /> PDF</button>
              {t.id === "Payroll Summary" && <button className="btn dark" onClick={() => generate(t.id, "Excel")}><Icon name="download" /> Excel</button>}
            </div>
          </section>
        ))}
      </div>
      <section className="card flush">
        <div className="card-head pad"><h3>Report history</h3></div>
        {!history.length ? <Empty>No reports generated yet.</Empty> : (
          <div className="table-wrap"><table>
            <thead><tr><th>Generated</th><th>Report</th><th>Format</th><th>Pay period</th><th>Generated by</th><th>File</th></tr></thead>
            <tbody>{history.map((r) => (
              <tr key={r.report_id}><td>{fmtDateTime(r.generated_at)}</td><td>{r.report_type}</td><td><span className="pill">{r.file_format}</span></td><td>{periodLabel(r)}</td><td>{r.generated_by_name}</td><td className="tiny">{r.file_path}</td></tr>
            ))}</tbody>
          </table></div>
        )}
      </section>
    </>
  );
}
